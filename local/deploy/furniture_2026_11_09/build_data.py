    rows.append(('Тип изделия', p['kind']))
    rows += [(k, v) for k, v in p['specs'] if k not in ('Производитель', 'Коллекция', 'Модель', 'Дизайнер')]
    lines = [f'<strong>{k}:</strong> {esc(v)}' for k, v in rows]
    p['preview_html'] = '<p>' + '<br/>'.join(lines) + '</p>'
    p['description_html'] = ''.join(f'<p>{esc(t)}</p>' for t in p['intro']) + '\n<h2>Особенности модели</h2>\n' \
        + li([esc(f) for f in p['features']] + lines)
    p['props'] = {PROPS[k]: v for k, v in p['specs']}
